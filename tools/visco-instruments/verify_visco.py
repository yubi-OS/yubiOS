def persistence_stats(applied_cells, regraded_passes, base_dbc, loaded_dbc,
                      regraded_dbcs):
    """C1 persistence: did the load's bit flips survive independent re-grading?

    Contract
    --------
    applied_cells : list of (row, axis) 2-tuples (or 2-lists) the load leg
        flipped. Direction is fixed: base bit 0 -> loaded bit 1. Rows are
        looked up by str(row) so int row ids match JSON string dict keys.
    regraded_passes : list of {"pass_id": str, "bits_by_row": {row: [12 bits]}}
        -- one entry per INDEPENDENT grader pass over the LOADED text. A pass
        missing a row simply does not credit that row's cells (counts as not
        persisted in that pass).
    base_dbc, loaded_dbc : floats, dBc of the base and loaded matrices.
    regraded_dbcs : list of float, dBc of each regraded pass (parallel to
        regraded_passes; len must match or ValueError).

    Persistence rule: a flip PERSISTS in a pass when the re-graded row credits
    bit 1 at that (row, axis) (bit 1 where base was 0). A cell is persisted
    OVERALL when it persists in EVERY pass (strictest rule; each pass is an
    independent blind re-grade, so survival must hold in all of them).
    per_pass_fractions carries the per-pass view; with one pass the two agree
    (the replay's 9/9 case is single-pass).

    Level math: delta_load = loaded - base; delta_regraded_passes[i] =
    regraded_dbcs[i] - base (positive = moved toward the null in the recorded
    frame; see module docstring sign conventions).

    Scorer variance (replay F1, first-class output):
      inter_pass_offset_dbc = max pairwise |dbc_i - dbc_j| across the REGRADED
        passes only (0.0 with fewer than 2 passes; a caller wanting to include
        another pass level appends it to regraded_dbcs/regraded_passes).
      max_bit_disagreement = over every (row, axis) cell present in >= 2
        passes, the number of pairwise pass pairs whose credited bits differ;
        max across cells (0 if no cell is covered by 2+ passes).

    Edge cases: applied_count 0 -> persistence_fraction 0.0 (nothing was
    flipped, nothing to persist); no regraded passes -> persisted_count 0,
    per_pass_fractions [], offset 0.0. Zero deltas are preserved exactly.
    Raises ValueError on regraded_dbcs/regraded_passes length mismatch.
    """
    if len(regraded_dbcs) != len(regraded_passes):
        raise ValueError("regraded_dbcs length must match regraded_passes")
    applied = [(str(cell[0]), int(cell[1])) for cell in applied_cells]
    applied_count = len(applied)

    per_pass_persisted = []
    for p in regraded_passes:
        bits_by_row = p.get("bits_by_row", {})
        count = 0
        for row, axis in applied:
            bits = bits_by_row.get(row)
            if bits is not None and axis < len(bits) and bits[axis] == 1:
                count += 1
        per_pass_persisted.append(count)

    per_pass_fractions = [
        (c / applied_count) if applied_count else 0.0
        for c in per_pass_persisted
    ]
    # overall: persisted in every pass
    persisted_count = 0
    for i in range(applied_count):
        if all(per_pass_persisted[p] > i for p in range(len(regraded_passes))):
            persisted_count += 1
    persistence_fraction = (persisted_count / applied_count) if applied_count else 0.0

    # scorer variance: pairwise dbc spread across regraded passes
    offset = 0.0
    for i in range(len(regraded_dbcs)):
        for j in range(i + 1, len(regraded_dbcs)):
            offset = max(offset, abs(regraded_dbcs[i] - regraded_dbcs[j]))

    # max pairwise bit disagreement across passes, per cell
    present = {}  # (row, axis) -> {pass_index: bit}
    for pi, p in enumerate(regraded_passes):
        for row, bits in p.get("bits_by_row", {}).items():
            for axis, bit in enumerate(bits):
                present.setdefault((str(row), axis), {})[pi] = bit
    max_bit_disagreement = 0  # MAX over cells of pairwise pass disagreements
    for cell, by_pass in present.items():
        if len(by_pass) < 2:
            continue
        idxs = sorted(by_pass)
        cell_pairs = 0
        for a in range(len(idxs)):
            for b in range(a + 1, len(idxs)):
                if by_pass[idxs[a]] != by_pass[idxs[b]]:
                    cell_pairs += 1
        max_bit_disagreement = max(max_bit_disagreement, cell_pairs)

    return {
        "applied_count": applied_count,
        "persisted_count": persisted_count,
        "persistence_fraction": persistence_fraction,
        "per_pass_fractions": per_pass_fractions,
        "level": {
            "dbc_base": float(base_dbc),
            "dbc_loaded": float(loaded_dbc),
            "dbc_regraded_passes": [float(d) for d in regraded_dbcs],
            "delta_load": float(loaded_dbc) - float(base_dbc),
            "delta_regraded_passes": [float(d) - float(base_dbc)
                                      for d in regraded_dbcs],
        },
        "scorer_variance": {
            "inter_pass_offset_dbc": offset,
            "max_bit_disagreement": max_bit_disagreement,
        },
    }


