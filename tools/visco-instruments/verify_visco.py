def _sign(x):
    """Return -1, 0, or +1 (exact zero only)."""
    if x > 0:
        return 1
    if x < 0:
        return -1
    return 0


def _mean(xs):
    return sum(xs) / len(xs)


def _solve_normal(cols, ys):
    """Least squares via normal equations; Gaussian elimination w/ pivoting.

    cols: list of column vectors (each len n), ys: list of n observations.
    Returns coefficient list len(cols), or None when the normal matrix is
    singular (pivot below threshold) -- callers skip that candidate.
    """
    n = len(ys)
    m = len(cols)
    ata = [[sum(cols[a][i] * cols[b][i] for i in range(n)) for b in range(m)]
           for a in range(m)]
    aty = [sum(cols[a][i] * ys[i] for i in range(n)) for a in range(m)]
    scale = max(1.0, max((abs(v) for row in ata for v in row), default=1.0))
    aug = [row[:] + [aty[i]] for i, row in enumerate(ata)]
    for c in range(m):
        p = max(range(c, m), key=lambda r: abs(aug[r][c]))
        if abs(aug[p][c]) < 1e-12 * scale:
            return None
        aug[c], aug[p] = aug[p], aug[c]
        pv = aug[c][c]
        for r in range(c + 1, m):
            f = aug[r][c] / pv
            if f:
                for k in range(c, m + 1):
                    aug[r][k] -= f * aug[c][k]
    x = [0.0] * m
    for r in range(m - 1, -1, -1):
        s = aug[r][m] - sum(aug[r][k] * x[k] for k in range(r + 1, m))
        x[r] = s / aug[r][r]
    return x


def _fit_columns(cols, ys):
    """Solve for coefficients of `cols` against `ys`, clipping negative
    exponential-arm amplitudes to 0 and re-solving the reduced system until no
    negative arm remains. Column 0 (the constant / ke column) is never clipped.
    Returns full coefficient vector (0.0 for clipped arms) or None if singular."""
    active = list(range(len(cols)))
    while True:
        sub = [cols[i] for i in active]
        sol = _solve_normal(sub, ys)
        if sol is None:
            return None
        neg = [active[j] for j in range(1, len(active)) if sol[j] < 0.0]
        if not neg:
            out = [0.0] * len(cols)
            for j, i in enumerate(active):
                out[i] = sol[j]
            return out
        active = [i for i in active if i not in neg]
        if len(active) == 0:  # unreachable: constant column always active
            return None


def _combinations(items, k):
    """Hand-rolled k-combinations (no itertools import; json/math-only rule)."""
    n = len(items)
    if k > n:
        return
    idx = list(range(k))
    while True:
        yield [items[i] for i in idx]
        j = k - 1
        while j >= 0 and idx[j] == n - k + j:
            j -= 1
        if j < 0:
            return
        idx[j] += 1
        for l in range(j + 1, k):
            idx[l] = idx[l - 1] + 1


