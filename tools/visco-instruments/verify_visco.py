DEFAULT_TAU_GRID_POINTS = 60
DEFAULT_TAU_LOG_LO = -2.0   # 1e-2
DEFAULT_TAU_LOG_HI = 4.0    # 1e4


def default_tau_grid():
    """Log-spaced tau grid, 60 points over 1e-2 .. 1e4 inclusive."""
    lo, hi, n = DEFAULT_TAU_LOG_LO, DEFAULT_TAU_LOG_HI, DEFAULT_TAU_GRID_POINTS
    return [10 ** (lo + (hi - lo) * i / (n - 1)) for i in range(n)]


def prony_fit(series, arms=2, tau_grid=None):
    """C3 deterministic Prony relaxation fit: value(t) ~= ke + sum k_j exp(-t/tau_j).

    Contract
    --------
    series : [{"t": number, "value": number}] ordered by ascending t; t may be
        a cycle index (SPEC sec.2.2 fallback when the runs store has no usable
        time column). Must contain at least arms+1 points or ValueError.
    arms : number of exponential arms, 1..3 (SPEC sec.2.4 caps K at 3; the
        grid-search cost grows combinatorially beyond that).
    tau_grid : optional explicit candidate tau list; default is the log-spaced
        60-point grid over 1e-2..1e4 (default_tau_grid()).

    Method (deterministic, no iterative optimizer): for every combination of
    `arms` distinct grid taus, build design columns [1, exp(-t/tau_j)...] and
    solve amplitudes by LINEAR LEAST SQUARES via pure-Python normal equations
    (Gaussian elimination with partial pivoting; small K so this is exact
    enough and fast). Negative exponential amplitudes are CLIPPED to 0 and
    the reduced system re-solved (repeat until no negative arm remains; the
    constant term ke is never clipped). Pick the (taus, amplitudes) minimizing
    SSE. Duplicate taus within a combination are skipped (singular).

    Determinism: same inputs -> same output on any platform, any language.
    The JS port must reproduce the same grid, the same combination order
    (ascending tau index), the same clip-and-resolve sequence, and the same
    tie-break (first minimal SSE encountered in that order) to stay
    fixture-parity-identical.

    Returns
    -------
    {ke, arms: [{k, tau}] (tau ascending, clipped arms carry k=0),
     fit_quality_r2: 1 - SSE/SST (SST about the mean; SST==0 -> 1.0 if the
       fit is exact else 0.0),
     fitted: [{t, value, fitted}], sse}
    """
    if not isinstance(arms, int) or arms < 1 or arms > 3:
        raise ValueError("arms must be an int in 1..3 (SPEC sec.2.4 caps K at 3)")
    ts = [float(p["t"]) for p in series]
    ys = [float(p["value"]) for p in series]
    if len(series) < arms + 1:
        raise ValueError("series needs at least arms+1 points")
    for i in range(1, len(ts)):
        if ts[i] < ts[i - 1]:
            raise ValueError("series must be ordered by ascending t")

    grid = sorted(set(float(t) for t in (tau_grid if tau_grid is not None
                                         else default_tau_grid())))
    n = len(ys)
    ybar = _mean(ys)
    sst = sum((y - ybar) ** 2 for y in ys)

    best = None  # (sse, taus, coefs)
    for taus in _combinations(grid, arms):
        if any(taus[j + 1] - taus[j] <= 1e-12 for j in range(arms - 1)):
            continue
        cols = [[1.0] * n]
        for tau in taus:
            cols.append([math.exp(-t / tau) for t in ts])
        coefs = _fit_columns(cols, ys)
        if coefs is None:
            continue
        sse = 0.0
        for i in range(n):
            pred = coefs[0]
            for j, tau in enumerate(taus):
                pred += coefs[j + 1] * cols[j + 1][i]
            sse += (ys[i] - pred) ** 2
        if best is None or sse < best[0] - 1e-15 * max(1.0, best[0]):
            best = (sse, taus, coefs)
    if best is None:
        raise ValueError("no solvable tau combination for the given series/grid")

    sse, taus, coefs = best
    fitted = []
    for i in range(n):
        pred = coefs[0]
        for j, tau in enumerate(taus):
            pred += coefs[j + 1] * math.exp(-ts[i] / tau)
        fitted.append({"t": ts[i], "value": ys[i], "fitted": pred})

    if sst == 0.0:
        r2 = 1.0 if sse < 1e-30 else 0.0
    else:
        r2 = 1.0 - sse / sst

    return {
        "ke": coefs[0],
        "arms": [{"k": coefs[j + 1], "tau": taus[j]} for j in range(arms)],
        "fit_quality_r2": r2,
        "fitted": fitted,
        "sse": sse,
    }


