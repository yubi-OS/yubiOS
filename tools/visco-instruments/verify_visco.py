def snapback_detect(series):
    """C4 snap-back detector with pre-registered-direction gate input.

    Contract
    --------
    series : [{"cycle", "predicted_delta", "realized_delta"}] in cycle order
        (the caller's ordering IS the consecutiveness order; cycles need not
        be contiguous integers). Deltas are in the recorded sign convention
        (see module docstring): realized +0.16 means dBc moved toward the null
        in the recorded frame. No polarity re-interpretation happens here.

    Rule
    ----
    Pre-registered direction for a cycle = sign(predicted_delta). A cycle is
    an INVERSION when sign(realized_delta) OPPOSES sign(predicted_delta):
      * realized_delta == 0 -> NEUTRAL, never opposed (a zero move carries no
        direction; replay gate treats it as no-evidence, not counter-evidence).
      * predicted_delta == 0 -> no pre-registered direction -> never opposed.
    Consecutive inversion cycles are grouped into RUNS (in series order; a
    neutral or agreeing cycle breaks a run).
    snapback = True iff any run has length >= 2 (SPEC sec.2.5: >=2 consecutive
    disagreeing cycles moving against the pre-registered direction).

    Returns
    -------
    {snapback: bool,
     inversion_runs: [[cycle, ...], ...] (each run's cycle values in order),
     run_lengths: [int, ...] (parallel to inversion_runs),
     verdict: "snapback" | "no_snapback",   # strings only, never auto-action
     gate_input: {"action": "halt_round" | "continue"},
     gate_noise_context: None}  # caller (C4 route) attaches scorer offset
        # here when grader-pass variance exceeds the effect being gated
        # (SPEC sec.2.7; replay F1: 5.77 dBc offset vs 0.64 effect size)

    Edge cases: empty series -> no_snapback/continue; single inversion cycle
    -> run length 1 -> no_snapback; all-neutral -> no_snapback.
    """
    runs = []
    current = []
    for point in series:
        cycle = point["cycle"]
        pred_sign = _sign(float(point["predicted_delta"]))
        real = float(point["realized_delta"])
        if real == 0.0 or pred_sign == 0:
            inversion = False
        else:
            inversion = _sign(real) != pred_sign
        if inversion:
            current.append(cycle)
        else:
            if current:
                runs.append(current)
                current = []
    if current:
        runs.append(current)

    run_lengths = [len(r) for r in runs]
    snapback = any(l >= 2 for l in run_lengths)
    return {
        "snapback": snapback,
        "inversion_runs": runs,
        "run_lengths": run_lengths,
        "verdict": "snapback" if snapback else "no_snapback",
        "gate_input": {"action": "halt_round" if snapback else "continue"},
        "gate_noise_context": None,
    }


