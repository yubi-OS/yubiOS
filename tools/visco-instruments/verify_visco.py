def _approx_equal(a, b, tol, path="$"):
    """Recursive structural comparison with float tolerance. Returns None if
    equal, else a human-readable mismatch description."""
    if isinstance(b, bool) or isinstance(a, bool):
        if a is b or a == b:
            return None
        return "%s: bool %r != %r" % (path, a, b)
    if a is None or b is None:
        if a is None and b is None:
            return None
        return "%s: %r != %r" % (path, a, b)
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        if abs(float(a) - float(b)) <= tol * (1.0 + abs(float(b))):
            return None
        return "%s: %r != %r (diff %g)" % (path, a, b, abs(float(a) - float(b)))
    if isinstance(a, str) and isinstance(b, str):
        return None if a == b else "%s: %r != %r" % (path, a, b)
    if isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            return "%s: list length %d != %d" % (path, len(a), len(b))
        for i, (x, y) in enumerate(zip(a, b)):
            err = _approx_equal(x, y, tol, "%s[%d]" % (path, i))
            if err:
                return err
        return None
    if isinstance(a, dict) and isinstance(b, dict):
        if set(a) != set(b):
            return "%s: keys %r != %r" % (path, sorted(map(str, a)),
                                          sorted(map(str, b)))
        for k in a:
            err = _approx_equal(a[k], b[k], tol, "%s.%s" % (path, k))
            if err:
                return err
        return None
    return "%s: type mismatch %r vs %r" % (path, type(a), type(b))


def _run_case(kind, case):
    """Run one fixture case through the matching instrument. Raises on error."""
    inp = case["input"]
    if kind == "persistence":
        return persistence_stats(inp["applied_cells"], inp["regraded_passes"],
                                 inp["base_dbc"], inp["loaded_dbc"],
                                 inp["regraded_dbcs"])
    if kind == "hysteresis":
        return hysteresis_rollup(inp["rows"])
    if kind == "prony":
        return prony_fit(inp["series"], inp.get("arms", 2), inp.get("tau_grid"))
    if kind == "snapback":
        return snapback_detect(inp["series"])
    raise ValueError("unknown fixture kind %r" % (kind,))


def selftest(verbose=True):
    """Run every fixture case + the hard replay anchors. Returns list of
    (name, ok, detail). Fixtures are the truth (frozen outputs of this very
    module), so any mismatch means the module changed or the port drifted."""
    checks = []

    def check(name, ok, detail=""):
        checks.append((name, bool(ok), detail))
        return ok

    with open(FIXTURE_PATH, "r") as f:
        fx = json.load(f)
    check("fixture_file_loads", fx.get("version") == 1,
          "version=%r" % (fx.get("version"),))

    for kind in ("persistence", "hysteresis", "prony", "snapback"):
        for case in fx.get(kind, []):
            name = "%s/%s" % (kind, case["name"])
            try:
                actual = _run_case(kind, case)
                err = _approx_equal(actual, case["expected"], FLOAT_TOL)
                check(name, err is None, err or "")
            except Exception as exc:  # noqa: BLE001 - report, don't crash
                check(name, False, "exception: %s" % (exc,))

    # ---- hard anchors (independent of the frozen expected values) ----
    hys_cases = {c["name"]: c for c in fx.get("hysteresis", [])}
