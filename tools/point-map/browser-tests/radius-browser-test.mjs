const results = [];
let failed = 0;
function check(name, ok, detail) {
  results.push({ name, ok: !!ok, detail: detail === undefined ? "" : String(detail) });
  if (!ok) failed++;
  console.log(`${ok ? "PASS" : "FAIL"}  ${name}${detail ? "  :: " + detail : ""}`);
}

const clipboardStub = `
  window.__clip = [];
  Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: function (t) { window.__clip.push(t); return Promise.resolve(); } } });
`;

const DESKTOP = { width: 1365, height: 900 };
const MOBILE = { width: 375, height: 720, isMobile: true, hasTouch: true };

async function clickSafe(page, sel) {
  await page.$eval(sel, (e) => e.scrollIntoView({ block: "center", inline: "center", behavior: "instant" }));
  await new Promise((r) => setTimeout(r, 250));
  await page.click(sel);
}

async function newPage(browser, viewport) {
  const page = await browser.newPage();
  await page.setViewport(viewport);
  const errors = [];
  page.on("pageerror", (e) => errors.push(String(e && e.message)));
  page.on("console", (m) => {
    if (m.type() !== "error") return;
    const t = m.text();
    if (/Failed to load resource|ERR_CERT|ERR_NAME_NOT_RESOLVED|ERR_INTERNET_DISCONNECTED|ERR_CONNECTION/.test(t)) return;
    errors.push("console: " + t);
  });
  await page.evaluateOnNewDocument(clipboardStub);
  page.__errors = errors;
  return page;
}

// Drive one candidate preview and return the radius section's text.
async function preview(page, action, name) {
  await page.evaluate(() => { document.getElementById("previewout").innerHTML = ""; document.getElementById("canderrors").style.display = "none"; });
  await page.select("#candaction", action);
  await page.evaluate((n) => {
    document.getElementById("candname").value = n;
    document.getElementById("candtext").value = "candidate body for the radius diagnostic fixture";
    document.getElementById("canddelta").value = "";
  }, name);
  await clickSafe(page, "#preview");
  await page.waitForFunction("document.getElementById('previewout').textContent.length > 40", { timeout: 20000 });
  return page.$eval("#previewout", (e) => e.textContent.replace(/\s+/g, " "));
}

