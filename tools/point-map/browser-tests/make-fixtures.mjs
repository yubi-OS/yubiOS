// Generates NETWORK FIXTURES (test doubles) for the browser test.
// The maps are produced by the REAL pointmap.js core so the shapes are honest;
// only the HTTP layer is faked. Nothing here contacts a live server.
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const code = fs.readFileSync(path.join(root, "pointmap.js"), "utf8");
const ctx = { console, module: { exports: {} }, exports: {}, window: {}, self: {}, TextEncoder, TextDecoder, Math, JSON, Date };
vm.createContext(ctx);
vm.runInContext(code, ctx);
const PM = ctx.PM || ctx.window.PM || ctx.module.exports.PM || ctx.module.exports;
if (!PM || typeof PM.runMap !== "function") throw new Error("could not load PM from pointmap.js");

const N = 14, D = 32, SEED = 20260906;
const opts = { d: 9, seed: SEED, K: 40, T: 0.05 };
// The map UI names free-text lines "line:<ordinal>"; the fixtures mirror that exactly so
// the frozen snapshot, the candidate corpus and the per_input rows line up.
const baseNames = Array.from({ length: N }, (_, i) => `line:${i}`);

const X = PM.synth(N, D, SEED);
const baseline = PM.runMap(X, { ...opts, names: baseNames });

// ---- ADD: one extra row, SAME frozen frame -> real ADD ledger ----
const addName = "skills/new-candidate/SKILL.md";
const Xadd = [...X.map((r) => r.slice()), X[0].map((v, j) => v + (j % 3 === 0 ? 0.41 : -0.23))];
const addMap = PM.runMap(Xadd, { ...opts, names: [...baseNames, addName], frame: baseline.frame });
const addLedger = PM.explainTransition(baseline, addMap);

// ---- CHANGE that does not move the point -> real "unchanged" CHANGE ledger ----
const changeName = baseNames[3];
const Xsame = X.map((r, i) => (i === 3 ? r.map((v) => v + 1e-9) : r.slice()));
const changeMap = PM.runMap(Xsame, { ...opts, names: baseNames.slice(), frame: baseline.frame });
const changeLedger = PM.explainTransition(baseline, changeMap);

const sha = (s) => "sha256-fixture-" + Buffer.from(String(s)).toString("hex").slice(0, 32);

const envelope = (map, ledger, target, extra) => ({
  preview: true,
  persisted: false,
  baseline_id: 51,
  map,
  comparison: { comparable: target.action !== "add" },
  comparison_note: target.action === "add"
    ? "name-set comparison is unsupported for ADD by the existing PM.compareMaps (same-name-set only); comparison.comparable is false and the per-anchor evidence is unchanged_anchor_count"
    : "per-name comparison on the inherited frozen frame",
  math_ledger: ledger,
  map_diagnostics: { available: false, reason: "FIXTURE: top-level map_diagnostics is deliberately unavailable; the UI must read map.math_diagnostics.per_input instead" },
  target,
  unchanged_source_count: N,
  unchanged_anchor_count: N,
  representation_drift_names: [],
  side_effects: { map_storage: false, repository: false, vectorize: false, embedding_cache: true },
  side_effects_note: "the content-hash embedding cache (env.SITE) may gain per-document vector entries via the existing embedDocuments path; no raw text, no credentials and no raw vectors are stored anywhere else, and no D1/Vectorize/repository write occurs",
  task_verdict: "not-tested",
  task_verdict_note: "geometry only: whether the candidate edit improves the underlying task is not tested here and must be checked by a task-specific independent verifier",
  ...extra,
});

const out = {
  _fixture: "TEST DOUBLE - generated by test/make-fixtures.mjs from the real pointmap.js core. Not a live server response.",
  baseline_id: 51,
  baseline_names: baseNames,
  add_name: addName,
  change_name: changeName,
  map_response: { id: 51, map: baseline, comparison: null },
  preview_add: envelope(addMap, addLedger, { action: "add", name: addName, before_sha256: null, after_sha256: sha("add"), noop: false, noop_note: null }),
  preview_change_unchanged: envelope(changeMap, changeLedger, { action: "change", name: changeName, before_sha256: sha("b"), after_sha256: sha("a"), noop: false, noop_note: null }),
};

fs.writeFileSync(path.join(here, "fixtures.json"), JSON.stringify(out));
console.log("ADD ledger kind    :", addLedger.kind, "delta", addLedger.ledger && addLedger.ledger.delta,
  "new_degree", addLedger.ledger && addLedger.ledger.new_degree,
  "touched", JSON.stringify(addLedger.ledger && addLedger.ledger.previous_isolates_touched_names));
console.log("CHANGE ledger kind :", changeLedger.kind, "moved_name", changeLedger.moved_name, "delta", changeLedger.ledger && changeLedger.ledger.delta);
console.log("reduction (ADD)    :", JSON.stringify(addLedger.reduction));
const m0 = baseline.math_diagnostics.per_input[0].margins[0];
console.log("margin[0] status   :", m0.status, "perturbation_bound", m0.perturbation_bound, "units", m0.units);
console.log("fixtures.json bytes:", fs.statSync(path.join(here, "fixtures.json")).size);
