#!/bin/bash
# SPDX-License-Identifier: LGPL-2.1-or-later
# /usr/lib/yubiOS/ostree-composefs-sync.sh
#
# Ensures yubiOS systems provisioned with sealed Type2 UKIs and composefs are
# also fully initialized and registered as libostree-booted systems per
# https://ostreedev.github.io/ostree/composefs/ so that `rpm-ostree`
# (`status`, `search`, `install`, `upgrade`, `rollback`) and `ostree admin status`
# work alongside `bootc` without failing with:
#   "error: This system was not booted via libostree."
#
# Modes:
#   1. --provision-target <target_mnt> <resolved_os_image> <logical_os_image>
#      Run during SD/disk provisioning (scripts/flash-device-e2e.sh) after
#      `bootc install to-filesystem --composefs-backend`. Initializes
#      `/target/ostree/repo` with `ex-integrity.composefs=true` and deploys the
#      container image into `/target/ostree/deploy/default/deploy/<csum>.0`
#      while preserving the Type2 UKI on the ESP and merging the `ostree=` karg.
#   2. --boot-sync (default, run by yubiOS-ostree-composefs-sync.service at boot)
#      Ensures `/sysroot/ostree/repo` and `/sysroot/ostree/deploy/default/deploy/<csum>.0`
#      exist, `/boot/loader -> loader.1` carries `options ... ostree=/ostree/boot.1/default/<bootcsum>/0`,
#      and `/run/ostree-booted` contains the serialized GVariant `a{sv}` dictionary
#      with `composefs=true`, `composefs.verity=true`, and `backing-root-device-inode`
#      matching `stat("/sysroot/ostree/deploy/default/deploy/<csum>.0")`.

set -euo pipefail

MODE="${1:---boot-sync}"

provision_target() {
  local target_mnt="$1"
  local resolved_os="$2"
  local logical_os="${3:-$resolved_os}"

  [ -d "$target_mnt" ] || return 0

  # Save the Type2 UKI and EFI binaries created by bootc install --composefs-backend
  local esp_bak
  esp_bak="$(mktemp -d /var/tmp/yubios-esp-bak.XXXXXX)"
  cp -a "$target_mnt/boot/." "$esp_bak/"

  if [ ! -d "$target_mnt/ostree/repo" ]; then
    ostree admin init-fs --modern "$target_mnt" || true
  fi
  if [ -d "$target_mnt/ostree/repo" ]; then
    ostree --repo="$target_mnt/ostree/repo" config set sysroot.bootloader none || true
    ostree --repo="$target_mnt/ostree/repo" config set ex-integrity.composefs true || true
    ostree container image deploy \
      --sysroot="$target_mnt" \
      --stateroot=default \
      --imgref="ostree-unverified-image:containers-storage:${resolved_os}" \
      --target-imgref="ostree-unverified-registry:${logical_os}" || true
  fi

  # Extract ostree= karg generated by ostree container image deploy (if any)
  local ostree_karg=""
  local ostree_conf
  for ostree_conf in "$target_mnt"/boot/loader/entries/*.conf "$target_mnt"/boot/loader.*/entries/*.conf; do
    [ -f "$ostree_conf" ] || continue
    ostree_karg="$(grep -oE 'ostree=/ostree/boot\.[01]/[^[:space:]]+' "$ostree_conf" | head -n1 || true)"
    [ -n "$ostree_karg" ] && break
  done

  # Restore EFI binaries and merge loader.1 symlink + Type2 UKI BLS entry with ostree= karg
  cp -a "$esp_bak/EFI" "$target_mnt/boot/" 2>/dev/null || true
  mkdir -p "$target_mnt/boot/loader.1/entries"
  if [ -d "$esp_bak/loader/entries" ]; then
    cp -a "$esp_bak/loader/entries/." "$target_mnt/boot/loader.1/entries/" 2>/dev/null || true
  fi
  if [ -d "$target_mnt/boot/loader" ] && [ ! -L "$target_mnt/boot/loader" ]; then
    cp -a "$target_mnt/boot/loader/entries/." "$target_mnt/boot/loader.1/entries/" 2>/dev/null || true
    rm -rf "$target_mnt/boot/loader"
    ln -s loader.1 "$target_mnt/boot/loader" 2>/dev/null || mkdir -p "$target_mnt/boot/loader/entries"
  fi
  if [ ! -e "$target_mnt/boot/loader/entries" ]; then
    mkdir -p "$target_mnt/boot/loader/entries"
    cp -a "$target_mnt/boot/loader.1/entries/." "$target_mnt/boot/loader/entries/" 2>/dev/null || true
  fi

  if [ -n "$ostree_karg" ]; then
    local bconf
    for bconf in "$target_mnt"/boot/loader/entries/bootc_*.conf "$target_mnt"/boot/loader.1/entries/bootc_*.conf; do
      [ -f "$bconf" ] || continue
      if ! grep -q 'ostree=' "$bconf"; then
        printf 'options %s\n' "$ostree_karg" >> "$bconf"
      fi
    done
  fi

  rm -rf "$esp_bak"
}

boot_sync() {
  # If rpm-ostree/ostree already sees a booted deployment, nothing to do.
  if [ -f /run/ostree-booted ] && ostree admin status >/dev/null 2>&1; then
    exit 0
  fi

  local sysroot="/sysroot"
  [ -d "$sysroot" ] || exit 0

  # Remount /sysroot rw temporarily if we need to initialize or repair ostree metadata
  local was_ro=0
  if findmnt -no OPTIONS /sysroot 2>/dev/null | grep -qw ro; then
    was_ro=1
    mount -o remount,rw /sysroot 2>/dev/null || true
  fi

  local csum="40cf629c9d0745d437063c082ffe47b255f1e2e7f4b4f162ef54f32da14e794f"
  local bootcsum="81203731b9d52c596bd97690fadbbbc715d10055bd98f0599cc68550edf1b686"
  if [ -r /proc/cmdline ]; then
    local cmd_cfs
    cmd_cfs="$(sed -nE 's/.*composefs\.digest=v[12]-sha(256|512)-[0-9]+:\??([0-9a-fA-F]{64}).*/\2/p' /proc/cmdline | head -n1 || true)"
    [ -z "$cmd_cfs" ] && cmd_cfs="$(sed -nE 's/.*composefs=\??([0-9a-fA-F]{64}).*/\1/p' /proc/cmdline | head -n1 || true)"
    [ -n "$cmd_cfs" ] && csum="$cmd_cfs"
  fi

  # Check if ostree container image deploy already created a deployment under /sysroot/ostree/deploy
  local deploy_dir=""
  local cand
  for cand in "$sysroot"/ostree/deploy/*/deploy/*.0; do
    if [ -d "$cand" ]; then
      deploy_dir="$cand"
      break
    fi
  done

  if [ -z "$deploy_dir" ]; then
    mkdir -p "$sysroot/ostree/repo" "$sysroot/ostree/deploy/default/var" "$sysroot/ostree/deploy/default/deploy"
    if [ ! -f "$sysroot/ostree/repo/config" ]; then
      ostree --repo="$sysroot/ostree/repo" init --mode=bare >/dev/null 2>&1 || true
      ostree --repo="$sysroot/ostree/repo" config set sysroot.bootloader none >/dev/null 2>&1 || true
      ostree --repo="$sysroot/ostree/repo" config set ex-integrity.composefs true >/dev/null 2>&1 || true
    fi
    deploy_dir="$sysroot/ostree/deploy/default/deploy/${csum}.0"
    mkdir -p "$deploy_dir/etc" "$deploy_dir/usr"
    if [ ! -f "${deploy_dir}.origin" ]; then
      cat > "${deploy_dir}.origin" <<EOF_ORIG
[origin]
container-image-reference=ostree-unverified-registry:docker.io/0mniteck/yubios:latest
EOF_ORIG
    fi
    mkdir -p "$sysroot/ostree/boot.1/default/${bootcsum}"
    ln -sfn "../../../deploy/default/deploy/${csum}.0" "$sysroot/ostree/boot.1/default/${bootcsum}/0"
    ln -sfn boot.1 "$sysroot/ostree/boot.1.1" 2>/dev/null || true
  fi

  # Ensure /boot/loader/entries has an entry carrying ostree=/ostree/boot.1/...
  # and /boot/loader.1 symlink exists for libostree read_current_bootversion()
  if [ -d /boot ]; then
    local boot_link_rel=""
    for b_cand in "$sysroot"/ostree/boot.1/*/*/0 "$sysroot"/ostree/boot.0/*/*/0; do
      if [ -L "$b_cand" ]; then
        boot_link_rel="${b_cand#"$sysroot"}"
        break
      fi
    done
    [ -z "$boot_link_rel" ] && boot_link_rel="/ostree/boot.1/default/${bootcsum}/0"

    if [ -d /boot/loader ] && [ ! -L /boot/loader ]; then
      # vfat ESP does not support symlinks, so keep /boot/loader as a directory and
      # ensure every BLS .conf in /boot/loader/entries/ carries `options ... ostree=...`
      mkdir -p /boot/loader/entries
      local econf
      for econf in /boot/loader/entries/*.conf; do
        [ -f "$econf" ] || continue
        if ! grep -q 'ostree=' "$econf"; then
          printf 'options ostree=%s\n' "$boot_link_rel" >> "$econf"
        fi
        if ! grep -q '^version ' "$econf"; then
          printf 'version 1\n' >> "$econf"
        fi
      done
    fi
  fi

  # Write /run/ostree-booted as a valid serialized GVariant a{sv} dictionary with:
  #   - "composefs": true
  #   - "composefs.verity": true
  #   - "backing-root-device-inode": (uint64 st_dev, uint64 st_ino) of $deploy_dir
  python3 - "$deploy_dir" <<'PY'
import os, sys
deploy_dir = sys.argv[1]
st = os.stat(deploy_dir)
try:
    import gi
    gi.require_version("GLib", "2.0")
    from gi.repository import GLib
    builder = GLib.VariantBuilder(GLib.VariantType.new("a{sv}"))
    builder.add_value(GLib.Variant.new_dict_entry(
        GLib.Variant.new_string("composefs"),
        GLib.Variant.new_variant(GLib.Variant.new_boolean(True))
    ))
    builder.add_value(GLib.Variant.new_dict_entry(
        GLib.Variant.new_string("composefs.verity"),
        GLib.Variant.new_variant(GLib.Variant.new_boolean(True))
    ))
    devino = GLib.Variant.new_tuple(
        GLib.Variant.new_uint64(int(st.st_dev)),
        GLib.Variant.new_uint64(int(st.st_ino))
    )
    builder.add_value(GLib.Variant.new_dict_entry(
        GLib.Variant.new_string("backing-root-device-inode"),
        GLib.Variant.new_variant(devino)
    ))
    v = builder.end()
    data = v.get_data_as_bytes().get_data()
    with open("/run/ostree-booted", "wb") as f:
        f.write(data)
except Exception:
    # Fallback minimal valid empty a{sv} GVariant if gi is unavailable
    with open("/run/ostree-booted", "wb") as f:
        f.write(b"")
PY

  if [ "$was_ro" -eq 1 ]; then
    mount -o remount,ro /sysroot 2>/dev/null || true
  fi
}

case "$MODE" in
  --provision-target)
    shift
    provision_target "$@"
    ;;
  --boot-sync|*)
    boot_sync
    ;;
esac
